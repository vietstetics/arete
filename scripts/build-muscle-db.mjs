// Regenerates features/muscles/data/muscleActions.js from the source CSV.
//   node scripts/build-muscle-db.mjs          → write the module
//   node scripts/build-muscle-db.mjs --check  → fail if the module is out of date
// The CSV in features/muscles/data/ is the source of truth; never edit the
// generated module by hand.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { parseSource } from '../features/muscles/services/parse.js';

const CSV = 'features/muscles/data/Muscle_Actions_Updated_Profiles.csv';
const OUT = 'features/muscles/data/muscleActions.js';

export function buildModule(csvBytes) {
  const { entries, notes } = parseSource(csvBytes.toString('utf8'));
  const meta = {
    source: 'Muscle_Actions_Updated_Profiles.csv',
    sha256: createHash('sha256').update(csvBytes).digest('hex'),
    columns: ['MUSCLE', 'RESISTANCE PROFILE', 'MUSCLE ACTION'],
    entryCount: entries.length,
    noteCount: notes.items.length,
  };
  return `// GENERATED by scripts/build-muscle-db.mjs from ${meta.source} — do not edit.
// Muscle regions and actions with their resistance-profile specifications.
// A foundation for workout creation: it holds no exercises. Exercise links
// live separately (features/muscles/repositories/exerciseLinks.js).

export const MUSCLE_DB_META = ${JSON.stringify(meta, null, 2)};

export const MUSCLE_ACTIONS = ${JSON.stringify(entries, null, 2)};

// Documentation from the source file — not muscle or exercise records.
export const MUSCLE_DB_NOTES = ${JSON.stringify(notes, null, 2)};
`;
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (isMain) {
  const next = buildModule(readFileSync(CSV));
  if (process.argv.includes('--check')) {
    const cur = readFileSync(OUT, 'utf8');
    if (cur !== next) { console.error(`${OUT} is out of date — run node scripts/build-muscle-db.mjs`); process.exit(1); }
    console.log(`${OUT} matches ${CSV}`);
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
